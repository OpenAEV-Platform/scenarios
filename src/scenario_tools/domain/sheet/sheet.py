"""The sheet of an entry, its README.md: what a reader of the catalogue needs to know before running
the scenario, from its metadata and its stored scenario, rendered the same way every time. Every
text of the entry is plain text (``markdown``); the only links are the sources', over HTTPS, and the
changelog's. The commands of the payloads of a time-based scenario are not shown; those of the
steps of a workflow are, as code, with the values they run with: a reviewer reads what each step
runs before the scenario can be imported."""

import math
import re
from collections.abc import Iterator, Mapping, Sequence
from typing import Any

from scenario_tools.domain.policy.exceptions import PolicyException
from scenario_tools.domain.policy.payloads import COMMAND_LIMIT, Payload, effective, payloads
from scenario_tools.domain.shared.stored import STEP_DATA, Origin, step_pointer
from scenario_tools.domain.shared.stored import injects as stored_injects
from scenario_tools.domain.shared.workflow import (
    StoredSettings,
    holds_workflow,
    step_identifier,
    step_waits,
    stored_settings,
    stored_steps,
)
from scenario_tools.domain.sheet.markdown import block, code, inline, plain

SHEET_LIMIT = 1024 * 1024  # the most a README.md is read with: a larger sheet could not be checked
NOTICE = (
    "<!-- This sheet is generated by `scenario-tools render` from scenario.yaml and scenario.json: "
    "edit them, then render it again. -->"
)
_NONE, _MISSING = "none", "—"
_UNITS = ((86400, "d"), (3600, "h"), (60, "min"), (1, "s"))
# A source shown as a link: an HTTPS address of the characters an address holds, nothing else; its
# host a plain name and port, never a user before it nor an escape in it, which would show a
# reader another name than the one the link goes to.
_LINK = re.compile(r"https://[A-Za-z0-9.\-:]+(?:[/?#][A-Za-z0-9\-._~:/?#\[\]@!$&'()*+,;=%]*)?")
_HOST = re.compile(r"https://([^/?#]*)")
_CONTRACT = "inject_injector_contract"
_PAYLOAD = "injector_contract_payload"


def duration(seconds: object) -> str:
    """A whole number of seconds in days, hours, minutes and seconds; any other value unknown."""
    if not isinstance(seconds, int) or isinstance(seconds, bool) or seconds < 0:
        return _MISSING
    parts = []
    for size, unit in _UNITS:
        count, seconds = divmod(seconds, size)
        if count:
            parts.append(f"{count} {unit}")
    return " ".join(parts) or "0 s"


def _text(value: object) -> str:
    return inline(value) if isinstance(value, str) else _MISSING


def _texts(values: object) -> str:
    """The texts of a list, in its order, as a cell or a line holds them."""
    if not isinstance(values, list):
        return _NONE
    return ", ".join(inline(value) for value in values if isinstance(value, str)) or _NONE


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [f"| {' | '.join(header)} |", f"|{'---|' * len(header)}"]
    lines += [f"| {' | '.join(row)} |" for row in rows]
    return "\n".join(lines)


def _glance(metadata: Mapping[str, Any]) -> str:
    return _table(
        ["", ""],
        [
            ["External ID", _text(metadata.get("external_id"))],
            ["Severity", _text(metadata.get("severity"))],
            ["Category", _text(metadata.get("category"))],
            ["Main focus", _text(metadata.get("main_focus"))],
            ["Platforms", _texts(metadata.get("platforms"))],
        ],
    )


def _threat(threat: Mapping[str, Any]) -> str:
    named = (("ttps", "Techniques"), ("cves", "CVEs"), ("intrusion_sets", "Intrusion sets"))
    return "\n".join(f"- {label}: {_texts(threat[key])}" for key, label in named if key in threat)


def _source(source: Mapping[str, Any]) -> str:
    """A source: a link only to an HTTPS address of the characters an address holds, its
    entities never decoded on the way, with its host in plain text, which no title can hide."""
    url = source.get("url")
    if not isinstance(url, str) or not _LINK.fullmatch(url):
        return f"- {_text(url)}"
    title = source.get("title")
    shown = inline(title) if isinstance(title, str) and title.strip() else inline(url)
    host = _HOST.match(url)[1]  # type: ignore[index]  # every link matches it
    return f"- [{shown}](<{url.replace('&', '&amp;')}>) {inline(f'({host})')}"


def _requirements(requires: Mapping[str, Any]) -> str:
    return "\n".join(
        [
            f"- OpenAEV: {_text(requires.get('openaev'))}",
            f"- Edition: {_text(requires.get('edition'))}",
            f"- Injectors: {_texts(requires.get('injectors'))}",
            f"- Executors: {_texts(requires.get('executors'))}",
        ]
    )


def _seconds(item: Mapping[str, Any]) -> float:
    """When an inject starts, in seconds; a time that is no whole number before any other."""
    seconds = item.get("inject_depends_duration")
    if isinstance(seconds, bool) or not isinstance(seconds, int) or seconds < 0:
        return -math.inf
    return float(seconds)


def _named(item: Mapping[str, Any], key: str) -> str:
    value = item.get(key)
    return value if isinstance(value, str) else ""


def depths(injects: Sequence[Mapping[str, Any]]) -> dict[str, int]:
    """How many injects each runs after, the longest such chain, by identifier: a parent comes
    before its children. Kahn's order, each inject queued once its parents are all placed, so
    that the run ends whatever the dependencies; the injects of a cycle, which the platform
    refuses, then take a depth from the parents placed before them, in the list's order."""
    parents = {_named(item, "inject_id"): _parents(item) for item in injects}
    children: dict[str, list[str]] = {name: [] for name in parents}
    waiting = dict.fromkeys(parents, 0)
    for name, named in parents.items():
        for parent in set(named) - {name}:
            if parent in parents:
                children[parent].append(name)
                waiting[name] += 1
    found = {name: 0 for name in parents if not waiting[name]}
    queue = list(found)
    for name in queue:  # each inject is queued once, when its last parent is placed
        for child in children[name]:
            waiting[child] -= 1
            if not waiting[child]:  # the parents are placed deepest last: this one is
                found[child] = found[name] + 1
                queue.append(child)
    for name in parents:
        if waiting[name]:
            found[name] = 1 + max((found[p] for p in parents[name] if p in found), default=-1)
    return found


def _ordered(stored: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    """The injects in the order they start, a parent before its children at the same time, then
    by title and identifier."""
    found = [  # the steps of a workflow are not part of the chain of injects
        stored_inject.inject
        for stored_inject in stored_injects(stored)
        if stored_inject.origin is Origin.INJECT
    ]
    chains = depths(found)
    return sorted(
        found,
        key=lambda item: (
            _seconds(item),
            chains[_named(item, "inject_id")],
            _named(item, "inject_title"),
            _named(item, "inject_id"),
        ),
    )


def _contract(item: Mapping[str, Any]) -> Mapping[str, Any]:
    contract = item.get(_CONTRACT)
    return contract if isinstance(contract, Mapping) else {}


def _parents(item: Mapping[str, Any]) -> list[str]:
    """The identifiers of the injects ``item`` runs after, as the platform exports them: each in
    the relationship of a dependency."""
    relations = item.get("inject_depends_on")
    found = []
    for relation in relations if isinstance(relations, list) else []:
        link = relation.get("dependency_relationship") if isinstance(relation, Mapping) else None
        parent = link.get("inject_parent_id") if isinstance(link, Mapping) else None
        if isinstance(parent, str):
            found.append(parent)
    return found


def _chain(injects: Sequence[Mapping[str, Any]]) -> str:
    if not injects:
        return "None."
    steps = {_named(item, "inject_id"): index for index, item in enumerate(injects, 1)}
    steps.pop("", None)  # an inject without an identifier is after nothing
    rows = []
    for index, item in enumerate(injects, 1):
        before = sorted(steps[name] for name in _parents(item) if name in steps)
        rows.append(
            [
                str(index),
                duration(item.get("inject_depends_duration")),
                ", ".join(str(step) for step in before),
                _text(item.get("inject_title")),
                _text(_contract(item).get("injector_contract_injector_type")),
            ]
        )
    return _table(["#", "From start", "After", "Title", "Injector"], rows)


def _payloads(injects: Sequence[Mapping[str, Any]]) -> str:
    found: set[tuple[str, str, str, str]] = set()
    for item in injects:
        payload = _contract(item).get(_PAYLOAD)
        if isinstance(payload, Mapping) and payload:  # an empty one is no payload, as exported
            found.add(
                (
                    _text(payload.get("payload_name")),
                    _text(payload.get("payload_external_id")),
                    _text(payload.get("payload_type")),
                    _texts(payload.get("payload_platforms")),
                )
            )
    if not found:
        return "None."
    return _table(["Name", "ID", "Type", "Platforms"], sorted(found))


# The steps of a workflow


_CAVEATS = (
    "- Safe mode is on, but OpenAEV does not enforce it when the scenario runs.",
    "- The limit of runs of a step is not enforced by OpenAEV either: it is written to a fixed "
    "value, so that what is reviewed is what applies.",
    "- The scenario names no target: targets are set by the operator after import, on the "
    "platform that runs it.",
)
_NO_LIMIT = 1 << 62  # for measuring a value too long to show


def _settings(settings: StoredSettings) -> str:
    lines = [
        f"- Each step times out after {inline(duration(settings.timeout_seconds))}."
        if settings.timeout_enabled
        else "- No step times out.",
        f"- Safe mode: {'on' if settings.safe_mode else 'off'}.",
        (
            f"- Pace: at most {_text(str(settings.attempts))} attempts per "
            f"{inline(duration(settings.period))}."
        )
        if settings.pace_enabled
        else "- Pace: none, each step starts as soon as it can.",
    ]
    return "\n".join(lines)


def _step_order(steps: list[tuple[int, Mapping[str, Any]]]) -> list[tuple[int, Mapping[str, Any]]]:
    """The steps in the order they can run: round by round, the steps whose awaited steps are
    all placed, by stable identifier, then by place in the file. Steps in a loop, which the
    checks refuse, come last, in that order."""
    remaining = sorted(steps, key=lambda found: (step_identifier(found[1]), found[0]))
    names = {step_identifier(step) for _, step in steps}
    placed: list[tuple[int, Mapping[str, Any]]] = []
    for _ in steps:  # a step is placed in a round, or never
        ready_ids = {step_identifier(step) for _, step in placed}
        ready = [
            found
            for found in remaining
            if all(name in ready_ids for name in step_waits(found[1])[0] if name in names)
        ]
        placed += ready
        remaining = [found for found in remaining if found not in ready]
    return placed + remaining


def _shown(payload: Payload, text: str) -> str | None:
    """``text`` with the values the payload runs it with, or ``None`` when that is too long to
    show."""
    return effective(payload, text, COMMAND_LIMIT)


def _too_long(payload: Payload, text: str) -> int:
    return len(effective(payload, text, _NO_LIMIT) or "")


def _code_of(label: str, payload: Payload, text: str) -> Iterator[str]:
    shown = _shown(payload, text)
    if shown is None:
        length = _too_long(payload, text)
        yield f"{label}: too long to show, {length} characters once its arguments are set."
    else:
        yield f"{label}:"
        yield block(shown)


def _commands(payload: Payload) -> Iterator[str]:
    """What a step's payload runs, each command as code, with the values it runs with."""
    fields = payload.fields
    for label, key, executor in (
        ("Command", "command_content", "command_executor"),
        ("Cleanup", "payload_cleanup_command", "payload_cleanup_executor"),
    ):
        if isinstance(fields.get(key), str):
            yield from _code_of(f"{label} ({_text(fields.get(executor))})", payload, fields[key])
    prerequisites = fields.get("payload_prerequisites")
    for prerequisite in prerequisites if isinstance(prerequisites, list) else []:
        if not isinstance(prerequisite, Mapping):
            continue
        for label, key in (("check", "check_command"), ("install", "get_command")):
            if isinstance(prerequisite.get(key), str):
                where = f"Prerequisite {label} ({_text(prerequisite.get('executor'))})"
                yield from _code_of(where, payload, prerequisite[key])
    arguments = fields.get("payload_arguments")
    for argument in arguments if isinstance(arguments, list) else []:
        if isinstance(argument, Mapping) and isinstance(argument.get("key"), str):
            yield from _argument(payload, argument["key"])


def _argument(payload: Payload, key: str) -> Iterator[str]:
    variable = "#{" + key + "}"
    value = _shown(payload, variable)
    label = f"- Argument {code(key)}"
    if value is None:
        yield f"{label}: too long to show, {_too_long(payload, variable)} characters."
    elif not value:
        yield f"{label}: empty."
    elif "\n" in value or "\r" in value:
        yield f"{label}:"
        yield block(value)
    else:
        yield f"{label}: {code(value)}"


def _waits(step: Mapping[str, Any], numbers: Mapping[str, int]) -> list[str]:
    awaited, others = step_waits(step)
    if not awaited and not others:
        return ["- Starts when the scenario is launched."]
    lines = []
    if awaited:
        known = sorted({numbers[name] for name in awaited if name in numbers})
        named = [f"step {number}" for number in known]
        if len(known) < len(set(awaited)):
            named.append("a step the scenario does not have")
        lines.append(f"- Waits for: {', '.join(named)}.")
    lines += [
        f"- Holds a condition of type {inline(kind)}, which the checks refuse for now."
        for kind in others
    ]
    return lines


def _step(
    number: int,
    step: Mapping[str, Any],
    numbers: Mapping[str, int],
    found: Mapping[str, Payload],
    pointer: str,
) -> Iterator[str]:
    inject = step.get(STEP_DATA)
    inject = inject if isinstance(inject, Mapping) else {}
    yield f"### {number}\\. {_text(inject.get('inject_title'))}"
    lines = _waits(step, numbers)
    lines.append(f"- Injector: {_text(_contract(inject).get('injector_contract_injector_type'))}")
    payload = found.get(f"{pointer}/{_CONTRACT}/{_PAYLOAD}")
    if payload is not None:
        lines.append(
            f"- Payload: {_text(payload.fields.get('payload_name'))} "
            f"{inline('(' + str(payload.fields.get('payload_external_id')) + ')')}"
        )
    yield "\n".join(lines)
    if payload is not None:
        yield from _commands(payload)


def _workflow(stored: Mapping[str, Any]) -> Iterator[str]:
    yield "## Workflow"
    yield _settings(stored_settings(stored))
    ordered = _step_order(list(stored_steps(stored)))
    numbers: dict[str, int] = {}
    for number, (_, step) in enumerate(ordered, 1):
        numbers.setdefault(step_identifier(step), number)  # the first of two of one identifier
    numbers.pop("", None)  # a step without an identifier is waited for by none
    found = {payload.pointer: payload for payload in payloads(stored)}
    yield "## Steps"
    for number, (index, step) in enumerate(ordered, 1):
        yield from _step(number, step, numbers, found, step_pointer(index))
    yield "## Caveats"
    yield "\n".join(_CAVEATS)


def _targets(targets: object) -> str:
    listed = (
        [target for target in targets if isinstance(target, Mapping)]
        if isinstance(targets, list)
        else []
    )
    if not listed:
        return "None: the scenario needs no target of the platform."
    return "\n".join(
        f"- {_text(target.get('placeholder'))}: {_text(target.get('description'))}"
        for target in listed
    )


def _exceptions(own: Sequence[PolicyException]) -> str:
    rows = [
        [
            inline(exception.code),
            inline(exception.field),
            inline(exception.justification),
        ]
        for exception in own
    ]
    return _table(["Rule", "Field", "Why"], rows)


def _sections(
    metadata: Mapping[str, Any], stored: Mapping[str, Any], exceptions: Sequence[PolicyException]
) -> Iterator[str]:
    yield NOTICE
    yield f"# {_text(metadata.get('name'))}"
    yield " · ".join(
        [
            f"Version {_text(metadata.get('version'))}",
            _text(metadata.get("status")),
            _text(metadata.get("type")),
        ]
    )
    description = metadata.get("description")
    if isinstance(description, str) and description.strip():
        yield plain(description)
    yield "## At a glance"
    yield _glance(metadata)
    threat = metadata.get("threat")
    yield "## Threat"
    yield _threat(threat) if isinstance(threat, Mapping) and threat else "None."
    sources = metadata.get("sources")
    yield "## Sources"
    listed = (
        [source for source in sources if isinstance(source, Mapping)]
        if isinstance(sources, list)
        else []
    )
    yield "\n".join(_source(source) for source in listed) or "None."
    requires = metadata.get("requires")
    yield "## Requirements"
    yield _requirements(requires if isinstance(requires, Mapping) else {})
    if holds_workflow(stored):
        yield from _workflow(stored)
    else:
        yield "## Chain of injects"
        yield _chain(_ordered(stored))
    yield "## Payloads"
    yield _payloads([found.inject for found in stored_injects(stored)])
    yield "## Targets to fill in"
    yield _targets(metadata.get("targets"))
    own = [exception for exception in exceptions if exception.entry == metadata.get("external_id")]
    if own:
        yield "## Policy exceptions"
        yield _exceptions(own)
    yield "## Versions"
    yield "What each version changed is in [CHANGELOG.md](CHANGELOG.md)."


def render_sheet(
    metadata: Mapping[str, Any], stored: Mapping[str, Any], exceptions: Sequence[PolicyException]
) -> str:
    """The README.md of the entry whose metadata and stored scenario are given, with the policy
    exceptions the maintainers granted it among ``exceptions``."""
    return "\n\n".join(_sections(metadata, stored, exceptions)) + "\n"
