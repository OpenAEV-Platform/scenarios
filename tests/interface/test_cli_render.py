"""The render command: each entry's sheet, its README.md, written from scenario.yaml and
scenario.json, or checked."""

import json
from pathlib import Path

import pytest

from scenario_tools.adapters.safe_readers import parse_yaml, yaml_bytes
from tests.interface.test_cli_validate import ENTRY_ID, _complete_entry, _invoke, _repository

EASM = "scenarios/techniques/easm"


def test_render_writes_the_sheet_and_check_then_passes(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    (entry / "README.md").unlink()

    written = _invoke(monkeypatch, "render", str(entry))
    checked = _invoke(monkeypatch, "render", "--check", str(entry))

    assert (written.exit_code, checked.exit_code) == (0, 0), written.output + checked.output
    sheet = (entry / "README.md").read_text(encoding="utf-8")
    assert sheet.startswith("<!-- This sheet is generated by `scenario-tools render`")
    assert "# EASM Scenario\n" in sheet
    assert json.loads(checked.stdout) == {"command": "render", "ok": True, "findings": []}


def test_render_again_writes_the_same_sheet(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    first = (entry / "README.md").read_bytes()

    _invoke(monkeypatch, "render", str(entry))

    assert (entry / "README.md").read_bytes() == first


@pytest.mark.parametrize("missing", [True, False])
def test_check_reports_a_sheet_missing_or_out_of_date(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, missing: bool
) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    if missing:
        (entry / "README.md").unlink()
    else:
        metadata = parse_yaml((entry / "scenario.yaml").read_bytes())
        metadata["description"] = "Another description"
        (entry / "scenario.yaml").write_bytes(yaml_bytes(metadata))

    result = _invoke(monkeypatch, "render", "--check", str(entry))

    assert result.exit_code == 1, result.output
    [finding] = json.loads(result.stdout)["findings"]
    assert (finding["code"], finding["path"]) == ("GEN-001", f"{EASM}/README.md")


def test_check_writes_nothing(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    (entry / "README.md").unlink()

    _invoke(monkeypatch, "render", "--check", str(entry))

    assert not (entry / "README.md").exists()


def test_a_readme_that_is_a_link_is_never_written_through(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    outside = tmp_path / "outside.md"
    outside.write_text("kept\n")
    (entry / "README.md").unlink()
    (entry / "README.md").symlink_to(outside)

    result = _invoke(monkeypatch, "render", str(entry))

    assert result.exit_code != 0
    assert outside.read_text() == "kept\n"


def test_an_entry_that_cannot_be_rendered_is_refused(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    entry = _complete_entry(monkeypatch, _repository(tmp_path))
    (entry / "scenario.json").unlink()
    (entry / "README.md").unlink()

    result = _invoke(monkeypatch, "render", str(entry))

    assert result.exit_code == 1, result.output
    [finding] = json.loads(result.stdout)["findings"]
    assert (finding["code"], finding["path"]) == ("GEN-001", f"{EASM}/scenario.yaml")
    assert not (entry / "README.md").exists()


def test_unusable_exceptions_are_the_environment_s_fault(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    root = _repository(tmp_path)
    entry = _complete_entry(monkeypatch, root)
    (root / "policy" / "data" / "exceptions.yaml").write_text("exceptions: {}\n")

    result = _invoke(monkeypatch, "render", str(entry))

    assert result.exit_code == 3
    assert "policy data cannot be used" in json.loads(result.stdout)["error"]


def test_the_sheet_of_a_chaining_entry_is_written_and_checked(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    entry = _repository(tmp_path) / "scenarios" / "techniques" / "chained"
    entry.mkdir(parents=True)
    chaining = Path(__file__).parents[2] / "tests" / "golden" / "chaining" / "two-steps.json"
    prepared = _invoke(
        monkeypatch, "normalize", str(chaining), "--out", str(entry), "--external-id", ENTRY_ID
    )
    assert prepared.exit_code == 0, prepared.output

    written = _invoke(monkeypatch, "render", str(entry))
    checked = _invoke(monkeypatch, "render", "--check", str(entry))

    assert (written.exit_code, checked.exit_code) == (0, 0), written.output + checked.output
    sheet = (entry / "README.md").read_text(encoding="utf-8")
    assert "## Steps" in sheet
    assert "```\nps aux --no-headers\n```" in sheet
